package org.bsl.cartonloading.buyers.lululemon.model;

import com.fasterxml.jackson.annotation.JsonFormat;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.mapping.Document;
import org.bsl.cartonloading.common.constants.AppConstants;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

@Data
@NoArgsConstructor
@Document(collection = AppConstants.Collection.SHIPPING_SCHEDULES)
public class ShippingSchedule {
    @Id
    private String id;
    private String buyerCode;
    @org.springframework.data.mongodb.core.mapping.Field("buyer_key")
    private String buyerKey = org.bsl.cartonloading.common.constants.AppConstants.Buyer.LULULEMON;
    private String orderId;
    /** Human-readable immutable schedule number generated by the server. */
    private String scheduleNo;
    /** Sales-entered display name; scheduleNo remains the stable identifier. */
    private String shippingName;
    /** Factory selected by Sales for this shipment schedule. */
    private String factoryCode;
    @JsonFormat(pattern = "yyyy-MM-dd")
    private LocalDate exFtyDate;
    /** Exact logical PO ids. Duplicate PO numbers remain separate records. */
    private List<String> poIds = new ArrayList<>();
    private String status;
    /** PASS, PENDING, ISSUES: separate from Shipping Schedule lifecycle status. */
    private String rfidReviewStatus;
    private String weighingOrderId;

    private String createdBy;
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime createdAt;
    private String reviewedBy;
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime reviewedAt;
    private String sentToWeightBy;
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime sentToWeightAt;
    private String completedBy;
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime completedAt;
    private String updatedBy;
    @JsonFormat(pattern = "yyyy-MM-dd'T'HH:mm:ss")
    private LocalDateTime updatedAt;
    private List<ShippingScheduleHistoryEntry> history = new ArrayList<>();
}
